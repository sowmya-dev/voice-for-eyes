export const TEMPLATES = { en, hi, te, kn };

export function formatDate({ year, month, day }, lang) {
  return new Intl.DateTimeFormat(LANGUAGES[lang].bcp47, { timeZone: 'UTC', year: 'numeric', month: 'long', ...(day ? { day: 'numeric' } : {}) })
    .format(new Date(Date.UTC(year, month - 1, day ?? 1)));
}

export function render({ id, slots = {} }, lang) {
  const table = TEMPLATES[lang] ?? en;
  const values = { ...slots };
  if (slots.month) values.date = formatDate(slots, lang);
  if (slots.purposeKey) values.purpose = table[`purpose.${slots.purposeKey}`];
  if (slots.direction) values.dir = table[`dir.${slots.direction}`];
  // Punctuation that a slot value already ends with is not doubled.
  return table[id].replace(/\{(\w+)\}([.।]?)/g, (_, key, stop) => {
    const value = String(values[key] ?? '');
    return /[.।!?]$/.test(value) ? value : value + stop;
  });
}

export const renderSegments = (segments, lang) => segments.map((s) => render(s, lang)).join(' ');
